function detectLang() {
  try {
    const saved = localStorage.getItem('mf-lang');
    if (saved === 'en' || saved === 'zh') return saved;
  } catch (e) {}
  const nav = (navigator.language || 'zh').toLowerCase();
  return nav.startsWith('zh') ? 'zh' : 'en';
}

let currentLang = detectLang();

function t(key, params) {
  let s = key;
  if (currentLang === 'en' && I18N.en[key] != null) s = I18N.en[key];
  if (params) {
    for (const k in params) s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), params[k]);
  }
  return s;
}

function applyLang() {
  document.documentElement.lang = currentLang === 'zh' ? 'zh-CN' : 'en';
  const btn = document.getElementById('langBtn');
  if (btn) btn.textContent = currentLang === 'zh' ? 'EN' : '中';
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  document.title = 'MediaFinder · ' + t('媒体文件快速查找工具');
  applyThemeUI();
  if (typeof refreshI18nUI === 'function') refreshI18nUI();
}

function toggleLang() {
  currentLang = currentLang === 'zh' ? 'en' : 'zh';
  try { localStorage.setItem('mf-lang', currentLang); } catch (e) {}
  applyLang();
}
